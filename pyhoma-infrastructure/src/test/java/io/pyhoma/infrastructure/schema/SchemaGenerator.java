package io.pyhoma.infrastructure.schema;

import io.pyhoma.domain.model.BaseEntity;
import io.pyhoma.domain.model.LongText;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.Table;
import java.io.IOException;
import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.math.BigDecimal;
import java.net.URISyntaxException;
import java.net.URL;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Locale;
import java.util.stream.Stream;

public final class SchemaGenerator {

    public enum Dialect { H2, POSTGRESQL, MYSQL, SQLSERVER, ORACLE }

    private SchemaGenerator() {
    }

    public static void main(String[] args) throws Exception {
        Path target = Path.of(args.length > 0 ? args[0] : "pyhoma-infrastructure/src/main/resources/db/migration");
        for (Dialect d : Dialect.values()) {
            Path dir = target.resolve(d.name().toLowerCase(Locale.ROOT));
            Files.createDirectories(dir);
            Files.writeString(dir.resolve("V1__baseline.sql"), generate(d), StandardCharsets.UTF_8);
            System.out.println("Generated " + dir.resolve("V1__baseline.sql"));
        }
    }

    public static List<Class<?>> entities() throws IOException, URISyntaxException, ClassNotFoundException {
        URL base = BaseEntity.class.getResource("BaseEntity.class");
        java.net.URI uri = base.toURI();
        if ("jar".equals(uri.getScheme())) {
            try {
                java.nio.file.FileSystems.newFileSystem(uri, java.util.Map.of());
            } catch (java.nio.file.FileSystemAlreadyExistsException ignored) {
            }
        }
        Path root = Path.of(uri).getParent();
        List<Class<?>> result = new ArrayList<>();
        try (Stream<Path> files = Files.walk(root)) {
            for (Path p : files.filter(f -> f.toString().endsWith(".class")).toList()) {
                String rel = root.relativize(p).toString().replace('\\', '/').replace('/', '.');
                String name = "io.pyhoma.domain.model." + rel.substring(0, rel.length() - ".class".length());
                Class<?> c = Class.forName(name);
                if (c.isAnnotationPresent(Entity.class)) {
                    result.add(c);
                }
            }
        }
        result.sort((a, b) -> table(a).compareTo(table(b)));
        return result;
    }

    public static String generate(Dialect dialect) throws Exception {
        StringBuilder sql = new StringBuilder();
        for (Class<?> entity : entities()) {
            sql.append(createTable(entity, dialect)).append('\n');
        }
        for (Class<?> entity : entities()) {
            for (String index : indexes(entity, dialect)) {
                sql.append(index).append('\n');
            }
        }
        return sql.toString();
    }

    private static String table(Class<?> entity) {
        return entity.getAnnotation(Table.class).name();
    }

    static String column(String field) {
        return field.replaceAll("([a-z0-9])([A-Z])", "$1_$2").toLowerCase(Locale.ROOT);
    }

    private static List<Field> persistentFields(Class<?> type) {
        List<Class<?>> chain = new ArrayList<>();
        for (Class<?> c = type; c != null && c != Object.class; c = c.getSuperclass()) {
            chain.add(c);
        }
        Collections.reverse(chain);
        List<Field> fields = new ArrayList<>();
        for (Class<?> c : chain) {
            for (Field f : c.getDeclaredFields()) {
                if (!Modifier.isStatic(f.getModifiers()) && !Modifier.isTransient(f.getModifiers()) && !f.isSynthetic()) {
                    fields.add(f);
                }
            }
        }
        return fields;
    }

    private static String createTable(Class<?> entity, Dialect d) {
        List<String> lines = new ArrayList<>();
        for (Field f : persistentFields(entity)) {
            lines.add("    " + column(f.getName()) + " " + columnType(f, d));
        }
        String body = String.join(",\n", lines);
        String suffix = d == Dialect.MYSQL ? " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci" : "";
        return "CREATE TABLE " + table(entity) + " (\n" + body + "\n)" + suffix + ";\n";
    }

    private static String columnType(Field f, Dialect d) {
        if (f.isAnnotationPresent(Id.class)) {
            return switch (d) {
                case H2, POSTGRESQL -> "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
                case MYSQL -> "BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY";
                case SQLSERVER -> "BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY";
                case ORACLE -> "NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY";
            };
        }
        Column col = f.getAnnotation(Column.class);
        boolean notNull = (col != null && !col.nullable()) || f.getType().isPrimitive();
        if (f.getName().equals("createdAt") || f.getName().equals("updatedAt")) {
            notNull = true;
        }
        String type = sqlType(f, col, d);
        return type + (notNull ? " NOT NULL" : "");
    }

    private static String sqlType(Field f, Column col, Dialect d) {
        Class<?> t = f.getType();
        if (t == String.class && f.isAnnotationPresent(LongText.class)) {
            return switch (d) {
                case H2, ORACLE -> "CLOB";
                case POSTGRESQL -> "TEXT";
                case MYSQL -> "LONGTEXT";
                case SQLSERVER -> "NVARCHAR(MAX)";
            };
        }
        if (t == String.class || f.isAnnotationPresent(Enumerated.class)) {
            int length = col == null ? 255 : col.length();
            return switch (d) {
                case ORACLE -> "VARCHAR2(" + length + " CHAR)";
                case SQLSERVER -> "NVARCHAR(" + length + ")";
                default -> "VARCHAR(" + length + ")";
            };
        }
        if (t == Long.class || t == long.class) {
            return d == Dialect.ORACLE ? "NUMBER(19)" : "BIGINT";
        }
        if (t == Integer.class || t == int.class) {
            return switch (d) {
                case ORACLE -> "NUMBER(10)";
                case SQLSERVER -> "INT";
                default -> "INTEGER";
            };
        }
        if (t == Boolean.class || t == boolean.class) {
            return switch (d) {
                case ORACLE -> "NUMBER(1)";
                case SQLSERVER -> "BIT";
                default -> "BOOLEAN";
            };
        }
        if (t == LocalDate.class) {
            return "DATE";
        }
        if (t == LocalDateTime.class) {
            return switch (d) {
                case MYSQL -> "DATETIME(6)";
                case SQLSERVER -> "DATETIME2";
                default -> "TIMESTAMP";
            };
        }
        if (t == BigDecimal.class) {
            int p = col == null || col.precision() == 0 ? 15 : col.precision();
            int s = col == null ? 2 : col.scale();
            return (d == Dialect.ORACLE ? "NUMBER(" : "DECIMAL(") + p + "," + s + ")";
        }
        throw new IllegalStateException("Unsupported type " + t + " on " + f);
    }

    private static List<String> indexes(Class<?> entity, Dialect d) {
        List<String> result = new ArrayList<>();
        String table = table(entity);
        for (Index index : entity.getAnnotation(Table.class).indexes()) {
            result.add("CREATE INDEX " + index.name() + " ON " + table + " (" + index.columnList() + ");");
        }
        for (Field f : persistentFields(entity)) {
            Column col = f.getAnnotation(Column.class);
            if (col != null && col.unique()) {
                String name = ("ux_" + table.replace("pyh_", "") + "_" + column(f.getName()));
                if (name.length() > 30) {
                    name = name.substring(0, 30);
                }
                result.add("CREATE UNIQUE INDEX " + name + " ON " + table + " (" + column(f.getName()) + ");");
            }
        }
        return result;
    }
}
